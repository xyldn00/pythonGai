# Запрашиваем у пользователя количество элементов, переводим ввод в целое число (int) и сохраняем в n
n = int(input("Введите количество чисел в кортеже: "))

# С помощью генератора кортежа поочередно запрашиваем у пользователя n чисел и создаем из них кортеж numbers
numbers = tuple(int(input(f"Введите число {i + 1}: ")) for i in range(n))

# Выводим на экран пустую строку для визуального разделения, текст и сам созданный кортеж
print("\nВаш кортеж:", numbers)

# Проверяем условие: если кортеж не пустой (его длина больше 0), то выполняем блок кода внутри if
if len(numbers) > 0:

    
    # 1) Вывод элементов и среза
    # Выводим первый элемент кортежа, обращаясь к нему по индексу 0
    print("Первый элемент:", numbers[0])
    
    # Выводим последний элемент кортежа, используя отрицательный индекс -1
    print("Последний элемент:", numbers[-1])
    
    # Индексы в Python начинаются с 0: 2-й элемент имеет индекс 1, 3-й — индекс 2.
    # Верхняя граница среза не включается, поэтому указываем [1:3].
    # Выводим срез: элементы с индексами 1 и 2 (элемент с индексом 3 не включится)
    print("Срез со второго по третий элемент:", numbers[1:3])

    # 2) Подсчет вхождений и поиск первого индекса
    # Запрашиваем у пользователя число, которое он хочет найти, и преобразуем его в целое число
    target = int(input("\nВведите число для поиска: "))
    
    # Считаем, сколько раз число target встречается в кортеже, с помощью метода .count()
    count = numbers.count(target)
    
    # Выводим количество найденных совпадений на экран, используя f-строку для подстановки значений
    print(f"Количество вхождений числа {target}: {count}")

    # Если число target было найдено хотя бы один раз (count больше 0)
    if count > 0:
        # Находим и выводим индекс самого первого появления числа target с помощью метода .index()
        print(f"Индекс первого вхождения: {numbers.index(target)}")
    # Если count равен 0 (число не найдено в кортеже)
    else:
        # Выводим сообщение, что искомого числа в кортеже нет
        print("Такого числа нет в кортеже.")
# Если самое первое условие (len(numbers) > 0) не выполнилось, то есть кортеж пуст
else:
    # Выводим сообщение о том, что кортеж пустой
    print("Кортеж пуст.")
